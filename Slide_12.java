// Array dalam Java
// Shortcut Inisialisasi Array
int[] anArray = {100,200,300,400};

// Akses Elemen Array
System.out.println(anArray[0]); //100
System.out.println(anArray[1]); //200

// Array Multidimensional
String[][] names = {
  {"Mr. ", "Mrs. ", "Ms. "},
  {"Smith", "Jones"}
};
System.out.println[0][0] + names[1][0]; // Mr. Smith
System.out.println[0][2] + names[1][1]; // Mr. Smith
